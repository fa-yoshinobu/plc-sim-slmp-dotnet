    public void RangeAndAccessErrorsMatchRealPlc(string name, string body, string expectedEndCode)
    {
        var profile = CpuProfiles.Get(CpuProfiles.IqR).With(pointOverrides: new Dictionary<string, uint> { ["D"] = 18432 });
        var engine = new SlmpEngine(new PlcModel(profile));
        var request = "500000FF03FF00" + body.Length.ToString("X4") + body;
        var response = Encoding.ASCII.GetString(engine.Process(FrameCodec.Parse(Encoding.ASCII.GetBytes(request)), new SlmpSession("t", "TEST")).Frame!);
        Assert.True(expectedEndCode == response.Substring(18, 4), $"{name}: 実機 {expectedEndCode} / Sim {response}");

        // 書込みが失敗したときは何も書かれていない（実機も D100・D18431・S0 は変わらなかった）
        var d = DeviceCatalog.FindByName("D")!;
        Assert.Equal(0, engine.Plc.Memory.ReadWords(d, 100, 1)[0]);
        Assert.Equal(0, engine.Plc.Memory.ReadWords(d, 18431, 1)[0]);
        Assert.False(engine.Plc.Memory.ReadBits(DeviceCatalog.FindByName("S")!, 0, 1)[0]);
    }

    /// <summary>実機 iQ-R 系（2026-10-10 計測）: LTC をモニタ登録して実行すると 4032、エラー情報のコマンドは 0403。</summary>
    [Fact]
    public void MonitorWithLongTimerContactFailsLikeRealPlc()
    {
        var engine = new SlmpEngine(new PlcModel(CpuProfiles.Get(CpuProfiles.IqR)));
        string Send(string body)
        {
            var request = "500000FF03FF00" + body.Length.ToString("X4") + body;
            return Encoding.ASCII.GetString(engine.Process(FrameCodec.Parse(Encoding.ASCII.GetBytes(request)), new SlmpSession("t", "TEST")).Frame!);
        }

        Assert.Equal("D00000FF03FF0000040000", Send("0010080100020100LTC*00000000"));
        Assert.Equal("D00000FF03FF000016403200FF03FF0004030000", Send("001008020000"));
        Assert.Equal("D00000FF03FF0000040000", Send("0010080100020200D***00000100LTC*00000000"));
        Assert.Equal("D00000FF03FF000016403200FF03FF0004030000", Send("001008020000"));
        Assert.Equal("D00000FF03FF0000040000", Send("0010080100000100D*000100"));
        Assert.Equal("D00000FF03FF00000800000000", Send("001008020000"));
    }
