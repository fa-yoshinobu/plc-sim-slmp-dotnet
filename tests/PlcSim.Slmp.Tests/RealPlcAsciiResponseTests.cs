    [Fact]
    public void ResponsesMatchRealPlc()
    {
        var profile = CpuProfiles.Get(CpuProfiles.IqR).With("R08PCPU", 0x4841);
        var engine = new SlmpEngine(new PlcModel(profile, new PlcSettings { RemoteResetAllowed = false, Units = new ushort[] { 1 } }));
        var n = 0;
        foreach (var (name, request, expected) in Measured)
        {
            var session = new SlmpSession($"conn{n++}", "TEST");
            var actual = Encoding.ASCII.GetString(engine.Process(FrameCodec.Parse(Encoding.ASCII.GetBytes(request)), session).Frame!);
            Assert.True(expected == actual, $"{name}: 実機 {expected} / Sim {actual}");
        }
    }

